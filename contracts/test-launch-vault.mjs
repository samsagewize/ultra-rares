import fs from 'node:fs';
import assert from 'node:assert/strict';
import ganache from 'ganache';
import solc from 'solc';
import { BrowserProvider, ContractFactory, parseUnits } from 'ethers';

const files = ['RareLaunchFeeVault.sol', 'MockRewardAsset.sol'];
const sources = Object.fromEntries(files.map((file) => [file, { content: fs.readFileSync(new URL(file, import.meta.url), 'utf8') }]));
const output = JSON.parse(solc.compile(JSON.stringify({ language: 'Solidity', sources, settings: { evmVersion: 'shanghai', optimizer: { enabled: true, runs: 200 }, outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } } } })));
const errors = (output.errors || []).filter(({ severity }) => severity === 'error');
assert.equal(errors.length, 0, errors.map(({ formattedMessage }) => formattedMessage).join('\n'));

const provider = new BrowserProvider(ganache.provider({ logging: { quiet: true } }));
const [owner, factory, stranger, treasury, launchToken, creator, nextOwner] = await Promise.all([0,1,2,3,4,5,6].map((i) => provider.getSigner(i)));
const deploy = async (file, name, signer, args=[]) => { const a=output.contracts[file][name]; return new ContractFactory(a.abi,`0x${a.evm.bytecode.object}`,signer).deploy(...args).then((c)=>c.waitForDeployment()); };
const expectRevert = async (promise,label) => { let reverted=false; try { const tx=await promise; if(tx?.wait)await tx.wait(); } catch { reverted=true; } assert.equal(reverted,true,label); };

const rare=await deploy('MockRewardAsset.sol','MockRewardAsset',owner,['RARE','RARE',18]);
const vault=await deploy('RareLaunchFeeVault.sol','RareLaunchFeeVault',owner,[await rare.getAddress(),await owner.getAddress(),await treasury.getAddress()]);
const gross=parseUnits('1000',18); const share=gross*300n/10000n;
assert.equal(await vault.withdrawalDestination(),await treasury.getAddress(),'withdrawal destination is immutable');
await expectRevert(vault.lockFeeSources(),'cannot lock an empty source list');
await expectRevert(vault.connect(stranger).setFeeSource(await factory.getAddress(),true),'only owner configures sources');
await (await vault.setFeeSource(await factory.getAddress(),true)).wait();
await expectRevert(vault.connect(factory).recordFee(await launchToken.getAddress(),await creator.getAddress(),gross,share),'recording before source lock fails');
await (await vault.lockFeeSources({gasLimit:200000})).wait();
await expectRevert(vault.setFeeSource(await stranger.getAddress(),true),'source lock is irreversible');
await expectRevert(vault.connect(stranger).recordFee(await launchToken.getAddress(),await creator.getAddress(),gross,share),'unauthorized source rejected');
await expectRevert(vault.connect(factory).recordFee(await launchToken.getAddress(),await creator.getAddress(),gross,share),'unfunded accounting rejected');
await (await rare.mint(await vault.getAddress(),share)).wait();
await expectRevert(vault.connect(factory).recordFee(await launchToken.getAddress(),await creator.getAddress(),gross,share+1n),'incorrect 3% share rejected');
await (await vault.connect(factory).recordFee(await launchToken.getAddress(),await creator.getAddress(),gross,share,{gasLimit:300000})).wait();
assert.equal(await vault.availableReserve(),share,'exact received share becomes available');
assert.equal(await vault.accountedBySource(await factory.getAddress()),share,'source accounting recorded');
assert.equal(await vault.accountedByLaunchToken(await launchToken.getAddress()),share,'token accounting recorded');
await expectRevert(vault.connect(stranger).release(share),'only owner releases');
await (await vault.release(share)).wait();
assert.equal(await rare.balanceOf(await treasury.getAddress()),share,'release can only reach immutable treasury');
await expectRevert(vault.release(1n),'released funds cannot be withdrawn twice');
const donation=parseUnits('5',18); await (await rare.mint(await vault.getAddress(),donation)).wait();
await (await vault.accountDonation(donation)).wait();
assert.equal(await vault.totalDonations(),donation,'direct RARE funding can be explicitly accounted');
await (await vault.release(donation)).wait();
assert.equal(await rare.balanceOf(await treasury.getAddress()),share+donation,'accounted donation releases only to treasury');
await (await vault.transferOwnership(await nextOwner.getAddress())).wait();
await expectRevert(vault.connect(stranger).acceptOwnership(),'only pending owner accepts');
await (await vault.connect(nextOwner).acceptOwnership()).wait();
assert.equal(await vault.owner(),await nextOwner.getAddress(),'two-step ownership completes');
console.log('Launch fee vault safety tests passed: 20 assertions');
